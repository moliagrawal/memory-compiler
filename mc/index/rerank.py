"""Second-stage interval reranker (B4): Boundary-aware cross-attention scoring."""

import torch
import torch.nn as nn
import torch.nn.functional as F
import numpy as np
from typing import List, Dict, Any, Tuple, Optional


class IntervalScorerNet(nn.Module):
    """
    Lightweight scoring network over candidate interval representations:
      Input tokens:
        - Query token [D]
        - Start boundary token [D]
        - Interval mean pooled token [D]
        - End boundary token [D]
        - Surrounding temporal context token [D]
      Outputs scalar interval compatibility score.
    """

    def __init__(self, d_model: int = 256, dropout: float = 0.1):
        super().__init__()
        self.d_model = d_model
        # Project 5 tokens through a 2-layer self-attention transformer
        encoder_layer = nn.TransformerEncoderLayer(
            d_model=d_model,
            nhead=4,
            dim_feedforward=d_model * 2,
            dropout=dropout,
            batch_first=True,
            activation="gelu"
        )
        self.transformer = nn.TransformerEncoder(encoder_layer, num_layers=2)
        self.scorer = nn.Sequential(
            nn.Linear(d_model * 5, d_model),
            nn.LayerNorm(d_model),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(d_model, 1)
        )

    def forward(self, interval_tokens: torch.Tensor) -> torch.Tensor:
        # interval_tokens is [B, 5, D]
        encoded = self.transformer(interval_tokens)  # [B, 5, D]
        flat = encoded.reshape(encoded.size(0), -1)   # [B, 5*D]
        score = self.scorer(flat).squeeze(-1)         # [B]
        return torch.sigmoid(score)


class IntervalReranker:
    """
    Second-stage candidate reranker (B4):
    Takes top-K segment candidates generated by B3, extracts boundary & interval tokens,
    and produces refined ranking scores.
    """

    def __init__(self, d_model: int = 256, device: str = "cpu"):
        self.device = device if (device == "cpu" or torch.cuda.is_available()) else "cpu"
        self.net = IntervalScorerNet(d_model=d_model).to(self.device)
        self.net.eval()
        self.d_model = d_model

    def build_interval_tokens(
        self,
        frame_feats: torch.Tensor,
        query_feat: torch.Tensor,
        start_idx: int,
        end_idx: int
    ) -> torch.Tensor:
        """
        Build 5 representative tokens for a candidate segment:
        [query, start_frame, interval_mean, end_frame, outside_context]
        """
        T = frame_feats.size(0)
        s = max(0, min(T - 1, start_idx))
        e = max(0, min(T - 1, end_idx))
        if s > e:
            s, e = e, s

        # 1. Query token
        t_query = query_feat

        # 2. Start boundary token
        t_start = frame_feats[s]

        # 3. Interval mean pooled token
        t_mean = frame_feats[s : e + 1].mean(dim=0)

        # 4. End boundary token
        t_end = frame_feats[e]

        # 5. Outside context token (pre and post)
        ctx_tokens = []
        if s > 0:
            ctx_tokens.append(frame_feats[:s].mean(dim=0))
        if e < T - 1:
            ctx_tokens.append(frame_feats[e + 1:].mean(dim=0))

        if ctx_tokens:
            t_ctx = torch.stack(ctx_tokens).mean(dim=0)
        else:
            t_ctx = torch.zeros_like(t_query)

        tokens = torch.stack([t_query, t_start, t_mean, t_end, t_ctx], dim=0)  # [5, D]
        return tokens

    @torch.inference_mode()
    def rerank_candidates(
        self,
        candidates: List[Dict[str, Any]],
        frame_features: np.ndarray,
        query_vector: np.ndarray,
        timestamps: np.ndarray,
        top_k: int = 5,
        alpha: float = 0.5
    ) -> List[Dict[str, Any]]:
        """
        Rerank top candidates:
          final_score = (1 - alpha) * candidate['score'] + alpha * rerank_score
        """
        if not candidates:
            return []

        # Project features to d_model if necessary
        f_dim = frame_features.shape[-1]
        f_tensor = torch.from_numpy(frame_features).float().to(self.device)
        q_tensor = torch.from_numpy(query_vector).float().to(self.device)

        if f_dim != self.d_model:
            # Linear projection or slice
            if f_dim > self.d_model:
                f_tensor = f_tensor[:, :self.d_model]
                q_tensor = q_tensor[:self.d_model]
            else:
                f_tensor = F.pad(f_tensor, (0, self.d_model - f_dim))
                q_tensor = F.pad(q_tensor, (0, self.d_model - f_dim))

        batch_tokens = []
        for cand in candidates:
            # Map start/end time to frame indices
            s_time = cand["start"]
            e_time = cand["end"]
            s_idx = int(np.argmin(np.abs(timestamps - s_time)))
            e_idx = int(np.argmin(np.abs(timestamps - e_time)))
            tokens = self.build_interval_tokens(f_tensor, q_tensor, s_idx, e_idx)
            batch_tokens.append(tokens)

        batch_tensor = torch.stack(batch_tokens, dim=0)  # [B, 5, D]
        rerank_scores = self.net(batch_tensor).cpu().numpy()

        reranked_cands = []
        for i, cand in enumerate(candidates):
            c_copy = dict(cand)
            r_score = float(rerank_scores[i])
            c_copy["rerank_score"] = round(r_score, 4)
            c_copy["combined_score"] = round((1 - alpha) * cand["score"] + alpha * r_score, 4)
            reranked_cands.append(c_copy)

        # Sort descending by combined score
        reranked_cands.sort(key=lambda x: -x["combined_score"])

        # Update ranks
        final_preds = []
        for rank, c in enumerate(reranked_cands[:top_k], 1):
            c["rank"] = rank
            c["score"] = c["combined_score"]
            final_preds.append(c)

        return final_preds
